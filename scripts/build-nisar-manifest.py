#!/usr/bin/env python3
"""Regenerate server/cache/nisar/manifest.mjs from the per-site snapshot files.

The server (server/nisar.mjs) imports this single manifest instead of listing
each site by hand. Adding a site is then a pure data step: drop its generated
files (``<site>.mjs``, ``<site>-rgb.mjs``, ``<site>-hh.mjs``,
``<site>-change.mjs``, ``<site>-recovery.mjs``, ``<site>-lenses.mjs``) into
server/cache/nisar/ and re-run this script. No renderer or registry edits.

Run:  .venv-nisar/bin/python scripts/build-nisar-manifest.py
"""

import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, 'server', 'cache', 'nisar')

# <site>-<artifact>.mjs  and  <site>.mjs (snapshot)
SUFFIXES = ('-rgb', '-hh', '-change', '-recovery', '-lenses')


def log(*a):
    print('[manifest]', *a, flush=True)


def discover_sites(files):
    sites = set()
    for name in files:
        if not name.endswith('.mjs'):
            continue
        base = name[:-4]
        if base == 'manifest':
            continue
        matched = False
        for suffix in SUFFIXES:
            if base.endswith(suffix) and len(base) > len(suffix):
                sites.add(base[: -len(suffix)])
                matched = True
                break
        if not matched:
            sites.add(base)
    return sorted(sites)


def main():
    files = os.listdir(CACHE)
    sites = discover_sites(files)

    lines = ['/** AUTO-GENERATED by scripts/build-nisar-manifest.py — do not edit by hand. */']
    snapshots, rgb, hh, change, recovery, lenses = [], [], [], [], [], []

    for site in sites:
        if os.path.exists(os.path.join(CACHE, f'{site}.mjs')):
            lines.append(f"import {{ {site}Snapshot }} from './{site}.mjs';")
            snapshots.append(site)
        if os.path.exists(os.path.join(CACHE, f'{site}-rgb.mjs')):
            lines.append(f"import {{ {site}RgbBase64 }} from './{site}-rgb.mjs';")
            rgb.append(site)
        if os.path.exists(os.path.join(CACHE, f'{site}-hh.mjs')):
            lines.append(f"import {{ {site}HhBase64 }} from './{site}-hh.mjs';")
            hh.append(site)
        if os.path.exists(os.path.join(CACHE, f'{site}-change.mjs')):
            lines.append(f"import {{ {site}ChangeBase64 }} from './{site}-change.mjs';")
            change.append(site)
        if os.path.exists(os.path.join(CACHE, f'{site}-recovery.mjs')):
            lines.append(f"import {{ {site}Recovery }} from './{site}-recovery.mjs';")
            recovery.append(site)
        if os.path.exists(os.path.join(CACHE, f'{site}-lenses.mjs')):
            lines.append(f"import {{ lensesSnapshot as {site}LensesSnapshot }} from './{site}-lenses.mjs';")
            lenses.append(site)

    lines.append('')
    lines.append(f'export const NISAR_SITES = {json.dumps(sites)};')
    lines.append(f'export const SNAPSHOTS = [{", ".join(s + "Snapshot" for s in snapshots)}];')
    lines.append('export const SNAPSHOT_RGB = {')
    for s in rgb:
        lines.append(f'  {s}: {s}RgbBase64,')
    lines.append('};')
    lines.append('export const SNAPSHOT_HH = {')
    for s in hh:
        lines.append(f'  {s}: {s}HhBase64,')
    lines.append('};')
    lines.append('export const SNAPSHOT_CHANGE = {')
    for s in change:
        lines.append(f'  {s}: {s}ChangeBase64,')
    lines.append('};')
    lines.append(f'export const RECOVERY = [{", ".join(s + "Recovery" for s in recovery)}];')
    lines.append(f'export const LENSES = [{", ".join(s + "LensesSnapshot" for s in lenses)}];')
    lines.append('')

    path = os.path.join(CACHE, 'manifest.mjs')
    with open(path, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines))
    log('wrote', os.path.relpath(path, ROOT), '| sites', sites)


if __name__ == '__main__':
    main()